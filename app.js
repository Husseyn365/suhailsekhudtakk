// Helper to get stored articles
function getStoredArticles() {
    const stored = localStorage.getItem("suhail_blog_posts_v4");
    if (!stored) {
        localStorage.setItem("suhail_blog_posts_v4", JSON.stringify(DEFAULT_ARTICLES));
        return DEFAULT_ARTICLES;
    }
    try {
        return JSON.parse(stored);
    } catch (e) {
        return DEFAULT_ARTICLES;
    }
}

