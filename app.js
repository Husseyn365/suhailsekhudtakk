function initPunchlineGenerator() {
    const display = document.getElementById("punchlineDisplay");
    const btn = document.getElementById("nextPunchlineBtn");
    if (!display || !btn) return;

    let currentIndex = 0;

    btn.addEventListener("click", () => {
        currentIndex = (currentIndex + 1) % DESI_PUNCHLINES.length;
        display.style.opacity = "0";
        setTimeout(() => {
            display.innerText = `"${DESI_PUNCHLINES[currentIndex]}"`;
            display.style.opacity = "1";
        }, 150);
    });
}

