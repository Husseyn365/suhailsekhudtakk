// Blogs Library Page (`blogs.html`)
// --------------------------------------------------------------------------
function initBlogsLibraryPage() {
    const grid = document.getElementById("blogsPageGrid");
    const tabs = document.querySelectorAll("#blogCategoryTabs .category-tab-btn");
    if (!grid) return;

    const articles = getStoredArticles();

    function render(category = "all") {
        grid.innerHTML = "";
        const filtered = category === "all" ? articles : articles.filter(a => a.category === category);

        if (filtered.length === 0) {
            grid.innerHTML = `<div style="grid-column: 1/-1; text-align: center; padding: 40px; color: var(--text-muted);">Is category me abhi koi mazmoon nahi hai. Bhai thoda intezar karo!</div>`;
            return;
        }

        filtered.forEach(art => {
            const card = document.createElement("a");
            card.className = "editorial-article-card";
            card.href = `blog-detail.html?id=${art.id}`;
            card.innerHTML = `
                <div>
                    <div class="card-meta-top">
                        <span class="card-pill pill-${art.category}">${art.categoryName || art.category}</span>
                        <span class="read-minutes"><i class="fa-regular fa-clock"></i> ${art.readTime}</span>
                    </div>
                    <h3 class="article-card-title">${art.title}</h3>
                    <p class="article-card-excerpt">${art.excerpt}</p>
                </div>
                <div class="card-footer-peer">
                    <span class="peer-author">By Your Peer</span>
                    <span class="read-link-arrow">Read Article <i class="fa-solid fa-arrow-right"></i></span>
                </div>
            `;
            grid.appendChild(card);
        });
    }

    render("all");

    tabs.forEach(tab => {
        tab.addEventListener("click", () => {
            tabs.forEach(t => t.classList.remove("active"));
            tab.classList.add("active");
            render(tab.getAttribute("data-category"));
        });
    });
}

// --------------------------------------------------------------------------
// Article Detail Page (`blog-detail.html`)
// --------------------------------------------------------------------------
function initArticleDetailPage() {
    const container = document.getElementById("articleDetailContainer");
    if (!container) return;

    const params = new URLSearchParams(window.location.search);
    const artId = params.get("id") || "art-1";

    const articles = getStoredArticles();
    const article = articles.find(a => a.id === artId) || articles[0];

    document.title = `${article.title} | Suhail Se Khudtakk`;
    const catEl = document.getElementById("detailCategory");
    if (catEl) catEl.innerText = article.categoryName || article.category;

    const titleEl = document.getElementById("detailTitle");
    if (titleEl) titleEl.innerText = article.title;

    const readTimeEl = document.getElementById("detailReadTime");
    if (readTimeEl) readTimeEl.innerText = article.readTime;

    const dateEl = document.getElementById("detailDate");
    if (dateEl) dateEl.innerText = article.date || "Recent";

    const contentEl = document.getElementById("detailContent");
    if (contentEl) contentEl.innerHTML = article.content;

    const promptEl = document.getElementById("detailPrompt");
    if (promptEl) promptEl.innerText = article.prompt || "Apne dil se poochein...";
}

// --------------------------------------------------------------------------
// Ask Page Form (`ask.html`)
// --------------------------------------------------------------------------
function initAskPageForm() {
    const form = document.getElementById("askPageForm");
    const success = document.getElementById("askPageSuccess");
    const reset = document.getElementById("askPageResetBtn");

    if (form) {
        form.addEventListener("submit", (e) => {
            e.preventDefault();

            const name = document.getElementById("askPageName").value.trim();
            const email = document.getElementById("askPageEmail").value.trim();
            const category = document.getElementById("askPageCategory").value;
            const message = document.getElementById("askPageMessage").value.trim();

            const newInquiry = {
                id: "inq-" + Date.now(),
                name: name || "Musafir (Anonymous Peer)",
                email: email,
                category: category,
                message: message,
                date: new Date().toLocaleDateString("en-US", { month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" }),
                status: "Pending"
            };

            const existing = JSON.parse(localStorage.getItem("suhail_inquiries") || "[]");
            existing.unshift(newInquiry);
            localStorage.setItem("suhail_inquiries", JSON.stringify(existing));

            form.style.display = "none";
            success.style.display = "block";
        });
    }

    if (reset) {
        reset.addEventListener("click", () => {
            form.reset();
            form.style.display = "block";
            success.style.display = "none";
        });
    }
}
